import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.dirname(fileURLToPath(new URL('../vite.config.js', import.meta.url)));

function normalizePath(file) {
    return file.replaceAll('\\', '/');
}

function findCssFiles(dir, ignoredFiles = new Set()) {
    if (!fs.existsSync(dir)) {
        return [];
    }

    return fs.readdirSync(dir, { withFileTypes: true })
        .flatMap((entry) => {
            const fullPath = path.join(dir, entry.name);

            if (entry.isDirectory()) {
                return findCssFiles(fullPath, ignoredFiles);
            }

            return entry.isFile() && entry.name.endsWith('.css') && !ignoredFiles.has(path.resolve(fullPath))
                ? [fullPath]
                : [];
        })
        .sort((a, b) => a.localeCompare(b));
}

function createTarget({ source, output }) {
    return {
        source: path.resolve(projectRoot, source),
        output: path.resolve(projectRoot, output),
    };
}

function discoverTargets(sourceRoot) {
    if (!fs.existsSync(sourceRoot)) {
        return [];
    }

    return fs.readdirSync(sourceRoot, { withFileTypes: true })
        .filter((entry) => entry.isDirectory())
        .map((entry) => ({
            source: path.join(sourceRoot, entry.name),
            output: path.join(sourceRoot, `${entry.name}.generated.css`),
        }))
        .filter(({ source }) => findCssFiles(source).length > 0);
}

export default function cssAutoImports(options = {}) {
    const sourceRoot = path.resolve(projectRoot, options.sourceRoot ?? 'resources/css');

    const getTargets = () => options.targets
        ? options.targets.map(createTarget)
        : discoverTargets(sourceRoot);

    const getGeneratedFiles = () => new Set(getTargets().map(({ output }) => output));

    const writeGeneratedFile = ({ source, output }) => {
        const imports = findCssFiles(source, getGeneratedFiles())
            .map((file) => {
                const relativePath = normalizePath(path.relative(path.dirname(output), file));

                return `@import "./${relativePath}";`;
            })
            .join('\n');

        fs.writeFileSync(output, [
            '/* This file is generated by vite-plugins/css-auto-imports.js. */',
            imports,
            '',
        ].join('\n'));
    };

    const writeAllGeneratedFiles = () => {
        getTargets().forEach(writeGeneratedFile);
    };

    return {
        name: 'css-auto-imports',
        buildStart() {
            writeAllGeneratedFiles();
        },
        configureServer(server) {
            server.watcher.add(normalizePath(path.join(sourceRoot, '**/*.css')));

            server.watcher.on('all', (_, file) => {
                const resolvedFile = path.resolve(file);
                const generatedFiles = getGeneratedFiles();

                if (!resolvedFile.endsWith('.css') || generatedFiles.has(resolvedFile)) {
                    return;
                }

                if (!resolvedFile.startsWith(sourceRoot)) {
                    return;
                }

                writeAllGeneratedFiles();
                server.ws.send({ type: 'full-reload' });
            });
        },
    };
}
